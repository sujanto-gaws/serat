//! Hashes, implemented locally for the same reason the PRNG is: the digest that
//! proves byte-identical output (NFR-MNT-02) must not depend on a crate that
//! could be unavailable offline or change behaviour.
//!
//! * SHA-256 — file and tree digests.
//! * CRC-32 (IEEE) — ZIP entries, PNG chunks.
//! * Adler-32 — zlib streams inside PNG.

